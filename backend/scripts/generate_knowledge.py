def main() -> None:
    cities_dir = KNOWLEDGE_DIR / "cities"
    cities_dir.mkdir(parents=True, exist_ok=True)

    # 1) 城市指南 markdown
    for city, meta in CITIES.items():
        lines = [
            f"# {city}旅行指南",
            "",
            f"**简介**：{meta['desc']}",
            "",
            f"- 省份：{meta['province']}",
            f"- 最佳旅行季节：{meta['best_season']}",
            f"- 特色标签：{'、'.join(meta['tags'])}",
            f"- 必尝美食：{'、'.join(meta['cuisine'])}",
            f"- 关键词：{'、'.join(meta['known_for'])}",
            "",
            "## 旅行亮点",
            *[f"- {a['name']}：{a['desc']}" for a in ATTRACTIONS[city][:4]],
            "",
            "## 住宿建议",
            *[f"- {h['name']}（约{h['price']}元/晚，评分{h['rating']}）：{h['desc']}" for h in HOTELS[city][:2]],
            "",
            "## 美食推荐",
            *[f"- {c}" for c in meta["cuisine"]],
            "",
            "## 小贴士",
            f"- {city}海拔与气候：{meta['desc']}",
            "- 旺季出行请提前订票订房，热门景点建议错峰游览。",
        ]
        (cities_dir / f"{city}.md").write_text("\n".join(lines), encoding="utf-8")

    # 2) 景点 JSON（保留索引）
    attr_items = []
    for city, items in ATTRACTIONS.items():
        for item in items:
            attr_items.append({"city": city, **item})
    (KNOWLEDGE_DIR / "attractions.json").write_text(
        json.dumps(attr_items, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    # 3) 酒店 JSON
    hotel_items = []
    for city, items in HOTELS.items():
        for item in items:
            hotel_items.append({"city": city, **item})
    (KNOWLEDGE_DIR / "hotels.json").write_text(
        json.dumps(hotel_items, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    # 4) 城市元数据（服务层使用）
    (KNOWLEDGE_DIR / "city_meta.json").write_text(
        json.dumps(CITIES, ensure_ascii=False, indent=1), encoding="utf-8"
    )

    # 5) 通用贴士
    (KNOWLEDGE_DIR / "tips.md").write_text(TIPS_MD.strip(), encoding="utf-8")

    n_attr = sum(len(v) for v in ATTRACTIONS.values())
    n_hotel = sum(len(v) for v in HOTELS.values())
    print(f"知识库生成完成：{len(CITIES)} 城市指南 / {n_attr} 景点 / {n_hotel} 酒店 / 贴士 1 篇")


if __name__ == "__main__":
    main()
