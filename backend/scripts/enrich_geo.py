def _fill(path: Path, table: dict[str, tuple[float, float]], force: bool) -> tuple[int, int, list[str]]:
    data = json.loads(path.read_text(encoding="utf-8"))
    added = skipped = 0
    missing: list[str] = []
    for item in data:
        if item.get("location") and not force:
            skipped += 1
            continue
        loc = table.get(item["name"])
        if loc:
            item["location"] = {"lat": loc[0], "lon": loc[1]}
            item["loc_source"] = "approx"
            added += 1
        else:
            missing.append(f"{item.get('city')}·{item['name']}")
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
    return added, skipped, missing


async def refine_with_amap() -> None:
    """配置了高德 Key 时，用真实 POI 坐标替换近似坐标（尽力而为）。"""
    svc = get_amap_service()
    if not svc.is_ready():
        print("（未配置高德 Key，跳过精确化；仍使用近似坐标）")
        return
    settings = get_settings()
    for fname in ("attractions.json", "hotels.json"):
        path = settings.knowledge_dir / fname
        data = json.loads(path.read_text(encoding="utf-8"))
        refined = 0
        for item in data:
            try:
                res = await svc._get(
                    "/v5/place/text",
                    {"keywords": item["name"], "city": item["city"], "citylimit": "true",
                     "page_size": 1, "show_fields": "business"},
                )
                pois = (res or {}).get("pois") or []
                if pois:
                    lon_s, lat_s = pois[0]["location"].split(",")
                    item["location"] = {"lat": round(float(lat_s), 6), "lon": round(float(lon_s), 6)}
                    item["loc_source"] = "amap"
                    addr = pois[0].get("address", "")
                    if addr and fname == "hotels.json":
                        item["address"] = addr
                    refined += 1
            except Exception as e:  # noqa: BLE001
                print(f"  高德精确化失败 {item['name']}: {e}")
        path.write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"{fname}: 高德精确化 {refined}/{len(data)} 条")


def main() -> None:
    force = "--force" in sys.argv
    settings = get_settings()
    for fname, table in (("attractions.json", ATTRACTION_LOC), ("hotels.json", HOTEL_LOC)):
        path = settings.knowledge_dir / fname
        added, skipped, missing = _fill(path, table, force)
        print(f"{fname}: 新增坐标 {added} 条，已有 {skipped} 条，未匹配 {len(missing)} 条")
        for m in missing:
            print(f"  ⚠️ 缺坐标: {m}")

    if "--amap" in sys.argv:
        asyncio.run(refine_with_amap())


if __name__ == "__main__":
    main()
