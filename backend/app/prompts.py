"""集中管理所有提示词（Prompt）。

- 所有 Agent 的系统提示词 / 指令集中在此，方便统一调优；
- 每个提示词都支持通过环境变量（.env 中的 `PROMPT_*`）覆盖，无需改代码即可调整人设；
- 覆盖优先级：环境变量 > 内置默认值。

对应环境变量一览：
  PROMPT_SYSTEM              主管协调器主提示词
  PROMPT_SUMMARY             会话历史摘要提示词
  PROMPT_PLANNER_PARSE       行程需求解析提示词（JSON 输出）
  PROMPT_FEEDBACK_LESSONS    反馈经验抽取提示词（JSON 输出）
  PROMPT_MEMORY_EXTRACT      长期记忆抽取提示词（JSON 输出）
  PROMPT_MCP_INSTRUCTIONS    MCP 服务器说明
"""
from __future__ import annotations

from app.config import get_settings

_settings = get_settings()


def _p(name: str, default: str) -> str:
    """取配置中的覆盖值（为空则用内置默认）。"""
    value = getattr(_settings, name, "")
    return value.strip() if value and value.strip() else default


